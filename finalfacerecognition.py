def draw_role_tracks(frame, tracks, role_map):
    """
    Draw bounding boxes with role labels.
    Patient and caregiver get their assigned colors.
    Any other detected person is labeled UNKNOWN with a dark grey box.

    Parameters
    ----------
    frame     : BGR numpy array
    tracks    : Nx5 array  [x1,y1,x2,y2, track_id]
    role_map  : dict  {track_id: 'patient' | 'caregiver' | None}
    """
    result = frame.copy()
    for row in tracks:
        x1, y1, x2, y2, tid = row
        x1, y1, x2, y2, tid = int(x1), int(y1), int(x2), int(y2), int(tid)

        role = role_map.get(tid)
        # Any track not confirmed as patient/caregiver is displayed as UNKNOWN
        if role not in ('patient', 'caregiver'):
            role = 'unknown'

        color = ROLE_COLOR[role]
        label = ROLE_LABEL_TEXT[role]

        cv2.rectangle(result, (x1, y1), (x2, y2), color, 2)

        font       = cv2.FONT_HERSHEY_DUPLEX
        font_scale = 0.65
        thickness  = 2
        (tw, th), baseline = cv2.getTextSize(label, font, font_scale, thickness)

        # filled label background
        pad = 4
        top    = max(y1 - th - 2*pad, 0)
        bottom = top + th + 2*pad
        cv2.rectangle(result, (x1, top), (x1 + tw + 2*pad, bottom), color, -1)
        cv2.putText(result, label, (x1 + pad, bottom - pad - baseline//2),
                    font, font_scale, (255, 255, 255), thickness, cv2.LINE_AA)

    return result

def draw_trajectories(frame, tracker, role_map=None):
    """
    Draws movement trail ONLY for patient and caregiver tracks.
    Unknown / third-party persons are skipped so no extra dots appear.

    Parameters
    ----------
    frame    : BGR numpy array (modified in place)
    tracker  : MemoryEnhancedBoTSORT instance
    role_map : dict {track_id: "patient"|"caregiver"} – confirmed roles only.
               If None, no trajectories are drawn (safe fallback).
    """
    if role_map is None:
        return frame

    for t in tracker.tracks:
        # Only draw trajectories for confirmed patient / caregiver tracks
        role = role_map.get(t.track_id)
        if role not in ("patient", "caregiver"):
            continue

        if len(t.trajectory) < 2:
            continue

        # Use fixed role color so trail matches the bounding box color
        color  = ROLE_COLOR[role]
        points = list(t.trajectory)

        for i in range(1, len(points)):
            pt1 = (int(points[i-1][0]), int(points[i-1][1]))
            pt2 = (int(points[i][0]),   int(points[i][1]))
            # Skip degenerate segments (same point) – these render as stray dots
            if pt1 == pt2:
                continue
            # Line fades (thinner) as it gets older
            thickness = int(np.sqrt(20 / float(i + 1)) * 2)
            cv2.line(frame, pt1, pt2, color, max(1, thickness), cv2.LINE_AA)

    return frame

