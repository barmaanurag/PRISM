class RoleTracker:
    """
    High-level class that combines:
      - YOLO person detection
      - MemoryEnhancedBoTSORT tracking
      - FaceIdentityManager for patient/caregiver labelling

    Occlusion handling
    ──────────────────
    • The tracker's LongTermMemory ensures a person re-entering the frame
      after full occlusion gets back the same track_id.
    • Because roles are keyed on track_id and locked permanently, the
      label survives occlusion automatically – no extra logic required.
    • Camera-motion compensation (GMC/ORB) stabilises bounding boxes when
      the CCTV camera pans or shakes.
    """

    def __init__(self, reid_model_path, yolo_model='yolo11s.pt',
                 conf_threshold=0.5):
        print("="*70)
        print("  Initialising RoleTracker")
        print("="*70)

        self.conf_threshold = conf_threshold

        print("\n[1/3] Loading YOLO detector…")
        self.detector = YOLO(yolo_model)
        print("  ✓ YOLO loaded")

        print("\n[2/3] Loading Re-ID feature extractor…")
        self.feature_extractor = EnhancedFeatureExtractor(
            model_path=reid_model_path, device=str(device),
            buffer_size=500, min_feature_quality=0.05
        )
        print("  ✓ Feature extractor loaded")

        print("\n[3/3] Initialising MemoryEnhancedBoTSORT tracker…")
        self.tracker = MemoryEnhancedBoTSORT(
            feature_extractor=self.feature_extractor,
            max_age=6000, min_hits=5,
            iou_threshold=0.4, lambda_iou=0.9, lambda_reid=0.1,
            reid_threshold=0.30, reid_buffer_size=150,
            memory_threshold=0.40, memory_size=6000
        )
        print("  ✓ Tracker ready (memory-enhanced, long-term buffer active)")

        # Face identity manager is built lazily in run()
        self.face_id_manager = None

    def build_gallery(self, dataset_dir='dataset'):
        print("\nBuilding face gallery from reference images…")
        self.face_id_manager = FaceIdentityManager()
        self.face_id_manager.build_gallery_from_folder(dataset_dir)
        print("  ✓ Gallery built")

    def process_frame(self, frame):
        """
        Detect → track → identify.

        Returns
        -------
        tracks   : Nx5  [x1,y1,x2,y2, track_id]
        role_map : dict {track_id: 'patient'|'caregiver'|None}
        """
        results    = self.detector(frame, verbose=False)[0]
        detections = []
        for box in results.boxes:
            if int(box.cls[0]) == 0:   # class 0 = person
                x1,y1,x2,y2 = box.xyxy[0].cpu().numpy()
                conf         = float(box.conf[0].cpu().numpy())
                if conf > self.conf_threshold:
                    detections.append([x1,y1,x2,y2,conf])

        det_arr = np.array(detections) if detections else np.empty((0,5))
        tracks  = self.tracker.update(frame, det_arr)

        if tracks.shape[0] == 0:
            return tracks, {}

        role_map = (self.face_id_manager.update(frame, tracks)
                    if self.face_id_manager else {})

        return tracks, role_map

