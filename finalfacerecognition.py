class FaceIdentityManager:
    """
    Uses InsightFace buffalo_l to:
      1. Build reference embeddings from uploaded patient/caregiver images.
      2. At runtime, detect faces inside person bounding boxes and compare
         them to the reference gallery to assign a role.

    Design decisions
    ─────────────────
    • Face detection runs on each person *crop* rather than the full frame;
      this is robust to scenes with many people and avoids cross-person confusion.
    • Similarity is cosine.  Thresholds are conservative so false positives
      are rare; unrecognised persons stay labelled "unknown".
    • Once a tracker ID is confirmed as patient or caregiver it is *locked*
      for the remainder of the video (stored in self.id_to_role).
    • Confirmation requires CONFIRM_HITS consecutive frames above threshold
      to suppress noise.
    """

    CONFIRM_HITS = 3          # frames above threshold needed to lock a role
    FACE_SIM_THRESHOLD = 0.30 # cosine similarity (InsightFace normed embeddings) — raised from 0.25 to reduce false matches

    def __init__(self, model_pack='buffalo_s', gpu_id=0):
        import insightface
        from insightface.app import FaceAnalysis
        print("Loading InsightFace model (buffalo_s)…")
        ctx = 0 if torch.cuda.is_available() else -1
        self.app = FaceAnalysis(
            name=model_pack, 
            allowed_modules=['detection', 'recognition'],
            providers=(['CUDAExecutionProvider'] if ctx == 0 else ['CPUExecutionProvider'])
        )
        self.app.prepare(ctx_id=ctx, det_size=(320, 320))
        print("  ✓ InsightFace ready")

        # Gallery: {role: [embedding, …]}
        self.gallery = {'patient': [], 'caregiver': []}

        # Runtime state
        self.track_sims = {}   # {track_id: {'patient': float, 'caregiver': float}}
        self.id_to_role = {}   # {track_id: 'patient'|'caregiver'}   (Current Frame)
        self.alpha      = 0.4  # EMA smoothing factor (faster response)
        
        # ReID-based appearance memory: when we confirm a face, store the body appearance
        self.role_reid_gallery = {'patient': [], 'caregiver': []}  # list of ReID embeddings per role
        self.reid_alpha = 0.45  # weight for ReID-based similarity updates (raised for stronger ReID reliance)

        # Role locking: once a track holds a role for CONFIRM_HITS consecutive
        # frames, it is "locked" — no other track can steal it.
        # {tid: {'role': str, 'held_frames': int, 'locked': bool}}
        self._role_locks = {}

        # Lost-role memory: when a LOCKED role disappears (track ID gone from
        # scene), remember it so we can transfer the role to a new track ID.
        # {role: {'reid_feats': [emb, ...], 'face_sims': dict, 'lost_frame': int}}
        self._lost_roles = {}
        self._frame_count = 0
        self.ROLE_TRANSFER_REID_THRESH = 0.35
        self.ROLE_TRANSFER_MAX_AGE = 300

    # ── gallery building ─────────────────────────────────────────────────────

    def _embed_image(self, img_bgr):
        """Return normalised face embedding from a BGR image, or None."""
        faces = self.app.get(img_bgr)
        if not faces:
            return None
        # Pick the largest face
        face  = max(faces, key=lambda f: (f.bbox[2]-f.bbox[0])*(f.bbox[3]-f.bbox[1]))
        emb   = face.normed_embedding.astype(np.float32)
        return emb / (np.linalg.norm(emb) + 1e-6)

    def build_gallery_from_folder(self, folder='dataset'):
        """
        Scans  dataset/patient/  and  dataset/caregiver/
        to build reference embeddings.
        """
        for role in ('patient', 'caregiver'):
            role_dir = os.path.join(folder, role)
            if not os.path.isdir(role_dir):
                print(f"  ⚠️  No folder found: {role_dir}"); continue
            loaded = 0
            for fname in sorted(os.listdir(role_dir)):
                if not fname.lower().endswith(('.jpg','.jpeg','.png','.bmp','.webp')):
                    continue
                img = cv2.imread(os.path.join(role_dir, fname))
                if img is None: continue
                emb = self._embed_image(img)
                if emb is not None:
                    self.gallery[role].append(emb)
                    loaded += 1
                else:
                    print(f"    ⚠️  No face detected in {fname}")
            print(f"  ✓ {role.capitalize()}: {loaded} reference face(s) loaded")

        assert (self.gallery['patient'] or self.gallery['caregiver']), \
            "❌ Gallery is empty – check dataset/ folders and image quality."

    # ── runtime identification ────────────────────────────────────────────────

    def _best_role_for_embedding(self, emb):
        """
        Compare emb against the gallery.
        Returns (best_role, best_similarity) or (None, 0).
        """
        best_role, best_sim = None, 0.0
        for role, refs in self.gallery.items():
            if not refs: continue
            sims = [float(np.dot(emb, r)) for r in refs]
            s    = max(sims)
            if s > best_sim:
                best_sim = s; best_role = role
        return best_role, best_sim

    def _get_face_in_crop(self, crop_bgr):
        """Detect face in a person crop; return normed embedding or None."""
        if crop_bgr is None or crop_bgr.size == 0:
            return None
        # Upscale very small crops for better detection
        h, w = crop_bgr.shape[:2]
        scale = 1.0
        if h < 80 or w < 40:
            scale = max(80/h, 40/w)
            crop_bgr = cv2.resize(crop_bgr, (int(w*scale), int(h*scale)))
        faces = self.app.get(crop_bgr)
        if not faces:
            return None
        face = max(faces, key=lambda f: (f.bbox[2]-f.bbox[0])*(f.bbox[3]-f.bbox[1]))
        emb  = face.normed_embedding.astype(np.float32)
        return emb / (np.linalg.norm(emb) + 1e-6)

    def update(self, frame_bgr, tracks, tracker=None):
        """
        Called once per frame.  Updates role assignments.

        Parameters
        ----------
        frame_bgr : full BGR frame
        tracks    : Nx5 numpy array [x1,y1,x2,y2, track_id]
        tracker   : MemoryEnhancedBoTSORT instance (for ReID feature access)

        Returns
        -------
        role_map  : dict {track_id: 'patient'|'caregiver'|None}
        """
        # Build a lookup of tracker's ReID features for each active track
        tracker_reid = {}
        if tracker is not None:
            for t in tracker.tracks:
                if t.state == 'confirmed':
                    tracker_reid[t.track_id] = t.get_feature()

        active_tids = []
        for row in tracks:
            x1, y1, x2, y2, tid = int(row[0]), int(row[1]), int(row[2]), int(row[3]), int(row[4])
            active_tids.append(tid)

            if tid not in self.track_sims:
                self.track_sims[tid] = {'patient': 0.0, 'caregiver': 0.0}

            # Extract person crop
            w, h = x2 - x1, y2 - y1
            x1c = max(0, int(x1 - w * 0.20))
            y1c = max(0, int(y1 - h * 0.20))
            x2c = min(frame_bgr.shape[1], int(x2 + w * 0.20))
            y2c = min(frame_bgr.shape[0], int(y2 + h * 0.20))
            crop = frame_bgr[y1c:y2c, x1c:x2c]

            face_updated = False
            emb = self._get_face_in_crop(crop)
            if emb is not None:
                sim_p = max([float(np.dot(emb, r)) for r in self.gallery['patient']] + [0.0])
                sim_c = max([float(np.dot(emb, r)) for r in self.gallery['caregiver']] + [0.0])
                
                # Ignore bad face crops (blurry, profile view) so they don't drag down the memory
                if max(sim_p, sim_c) > 0.25:
                    face_updated = True
                    if self.track_sims[tid]['patient'] == 0.0 and self.track_sims[tid]['caregiver'] == 0.0:
                        self.track_sims[tid]['patient'] = sim_p
                        self.track_sims[tid]['caregiver'] = sim_c
                    else:
                        self.track_sims[tid]['patient'] = (1 - self.alpha) * self.track_sims[tid]['patient'] + self.alpha * sim_p
                        self.track_sims[tid]['caregiver'] = (1 - self.alpha) * self.track_sims[tid]['caregiver'] + self.alpha * sim_c
                    
                    # Store this person's ReID (clothing) embedding alongside their best role
                    if tid in tracker_reid:
                        best_role = 'patient' if sim_p > sim_c else 'caregiver'
                        if max(sim_p, sim_c) > self.FACE_SIM_THRESHOLD:
                            reid_feat = tracker_reid[tid] / (np.linalg.norm(tracker_reid[tid]) + 1e-6)
                            self.role_reid_gallery[best_role].append(reid_feat)
                            # Keep gallery small (max 20 embeddings per role)
                            if len(self.role_reid_gallery[best_role]) > 20:
                                self.role_reid_gallery[best_role].pop(0)

            # FALLBACK: If no face detected, use ReID (clothing/body) appearance matching
            if not face_updated and tid in tracker_reid:
                reid_feat = tracker_reid[tid]
                reid_feat_norm = reid_feat / (np.linalg.norm(reid_feat) + 1e-6)
                
                reid_sim_p = 0.0
                reid_sim_c = 0.0
                if self.role_reid_gallery['patient']:
                    sims = [float(np.dot(reid_feat_norm, r)) for r in self.role_reid_gallery['patient']]
                    reid_sim_p = max(sims)
                if self.role_reid_gallery['caregiver']:
                    sims = [float(np.dot(reid_feat_norm, r)) for r in self.role_reid_gallery['caregiver']]
                    reid_sim_c = max(sims)
                
                # Only update if ReID match is strong enough AND discriminative.
                # The candidate must match one role clearly better than the other
                # to prevent cross-assignment (e.g. caregiver labeled as patient).
                if max(reid_sim_p, reid_sim_c) > 0.40:
                    margin = abs(reid_sim_p - reid_sim_c)
                    if margin > 0.05:  # must be at least 5% more similar to one role
                        # Scale ReID scores to face-similarity range
                        scaled_p = reid_sim_p * 0.85
                        scaled_c = reid_sim_c * 0.85
                        if self.track_sims[tid]['patient'] == 0.0 and self.track_sims[tid]['caregiver'] == 0.0:
                            self.track_sims[tid]['patient'] = scaled_p
                            self.track_sims[tid]['caregiver'] = scaled_c
                        else:
                            self.track_sims[tid]['patient'] = (1 - self.reid_alpha) * self.track_sims[tid]['patient'] + self.reid_alpha * scaled_p
                            self.track_sims[tid]['caregiver'] = (1 - self.reid_alpha) * self.track_sims[tid]['caregiver'] + self.reid_alpha * scaled_c

        # ══════════════════════════════════════════════════════════════
        # ROLE ASSIGNMENT  (locked-role-first, then greedy matching)
        # ══════════════════════════════════════════════════════════════
        role_map = {}
        assigned_roles = set()
        assigned_tids = set()
        prev_roles = dict(self.id_to_role)
        self.id_to_role = {}
        self._frame_count += 1
        active_set = set(active_tids)

        # ── Step 1: Carry forward roles in _role_locks ─────────────────
        # Tracks already in _role_locks get their role pre-assigned.
        # If held long enough, they become locked (cannot be stolen).
        for tid in list(self._role_locks):
            if tid not in active_set:
                continue  # track disappeared — handled in Step 4
            lock = self._role_locks[tid]
            role = lock['role']
            if role in assigned_roles:
                continue
            role_map[tid] = role
            self.id_to_role[tid] = role
            assigned_tids.add(tid)
            assigned_roles.add(role)
            lock['held_frames'] += 1
            # Promote to locked after CONFIRM_HITS consecutive frames
            if lock['held_frames'] >= self.CONFIRM_HITS and not lock['locked']:
                lock['locked'] = True
                score = self.track_sims.get(tid, {}).get(role, 0.0)
                src = "face" if score > 0.35 else "ReID"
                print(f"  🔒 Locked track {tid} → {role.upper()} (score {score:.3f}, via {src})")

        # ── Step 2: Greedy matching for UNLOCKED tracks ──────────────
        candidates = []
        for tid in active_tids:
            if tid in assigned_tids:
                continue  # already locked
            for role in ['patient', 'caregiver']:
                if role in assigned_roles:
                    continue  # role already taken by a locked track
                score = self.track_sims.get(tid, {}).get(role, 0.0)
                if score >= self.FACE_SIM_THRESHOLD:
                    candidates.append((score, tid, role))

        candidates.sort(reverse=True, key=lambda x: x[0])

        for score, tid, role in candidates:
            if tid in assigned_tids or role in assigned_roles:
                continue
            role_map[tid] = role
            self.id_to_role[tid] = role
            assigned_tids.add(tid)
            assigned_roles.add(role)
            # Start lock tracking (first frame with this role)
            self._role_locks[tid] = {'role': role, 'held_frames': 1, 'locked': False}
            src = "face" if score > 0.35 else "ReID"
            print(f"  🏷️  Tentative: track {tid} → {role.upper()} (score {score:.3f}, via {src}, locking in {self.CONFIRM_HITS - 1} frames)")
            # Remove from lost roles if this role was recovered
            self._lost_roles.pop(role, None)

        # ── Step 3: Role transfer for lost roles via ReID ────────────
        for role in ['patient', 'caregiver']:
            if role in assigned_roles:
                continue
            if role not in self._lost_roles:
                continue
            lost = self._lost_roles[role]
            if (self._frame_count - lost['lost_frame']) > self.ROLE_TRANSFER_MAX_AGE:
                del self._lost_roles[role]
                continue
            best_tid, best_sim = None, self.ROLE_TRANSFER_REID_THRESH
            lost_feats = lost['reid_feats']
            other_role = 'caregiver' if role == 'patient' else 'patient'
            for tid in active_tids:
                if tid in assigned_tids:
                    continue
                if tid not in tracker_reid:
                    continue
                feat = tracker_reid[tid]
                feat_norm = feat / (np.linalg.norm(feat) + 1e-6)
                sims = [float(np.dot(feat_norm, lf)) for lf in lost_feats]
                avg_sim = (0.5 * np.mean(sims) + 0.5 * np.max(sims)) if sims else 0.0
                # Discrimination check
                other_sim = 0.0
                if self.role_reid_gallery[other_role]:
                    other_sims = [float(np.dot(feat_norm, r)) for r in self.role_reid_gallery[other_role]]
                    other_sim = max(other_sims)
                if other_sim >= avg_sim:
                    continue
                if avg_sim > best_sim:
                    best_sim = avg_sim
                    best_tid = tid
            if best_tid is not None:
                role_map[best_tid] = role
                self.id_to_role[best_tid] = role
                assigned_tids.add(best_tid)
                assigned_roles.add(role)
                self.track_sims[best_tid] = dict(lost['face_sims'])
                self._role_locks[best_tid] = {'role': role, 'held_frames': self.CONFIRM_HITS, 'locked': True}
                print(f"  🔄 Role transfer: track {best_tid} → {role.upper()} (ReID sim {best_sim:.3f})")
                del self._lost_roles[role]

        # ── Step 4: Detect truly lost roles (track gone from scene) ──
        # Only save lost-role memory when a LOCKED track disappears from
        # active_tids. Role "theft" by another track does NOT trigger this.
        for tid in list(self._role_locks):
            if tid in active_set:
                continue  # track still alive
            lock = self._role_locks[tid]
            role = lock['role']
            if not lock['locked']:
                del self._role_locks[tid]
                continue  # wasn't locked yet, just discard
            # Track is gone AND was locked — save for transfer
            if role not in assigned_roles:
                feats = []
                if tid in tracker_reid:
                    feat = tracker_reid[tid] / (np.linalg.norm(tracker_reid[tid]) + 1e-6)
                    feats = [feat]
                elif self.role_reid_gallery.get(role):
                    feats = list(self.role_reid_gallery[role])
                if feats:
                    self._lost_roles[role] = {
                        'reid_feats': feats[-10:],
                        'face_sims': dict(self.track_sims.get(tid, {'patient': 0.0, 'caregiver': 0.0})),
                        'lost_frame': self._frame_count,
                    }
                    print(f"  ⚠️  Role '{role.upper()}' lost (track {tid} gone) — saved for transfer")
            del self._role_locks[tid]

        # Any remaining active tracks are Unknown
        for tid in active_tids:
            if tid not in assigned_tids:
                role_map[tid] = None
                
        return role_map

    def get_role_map(self):
        """Return the complete locked-role dictionary."""
        return dict(self.id_to_role)

