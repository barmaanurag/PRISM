def _iou_distance(bboxes1, bboxes2):
    if len(bboxes1) == 0 or len(bboxes2) == 0:
        return np.zeros((len(bboxes1), len(bboxes2)))
    b1 = np.expand_dims(bboxes1, 1); b2 = np.expand_dims(bboxes2, 0)
    xi1 = np.maximum(b1[...,0], b2[...,0]); yi1 = np.maximum(b1[...,1], b2[...,1])
    xi2 = np.minimum(b1[...,2], b2[...,2]); yi2 = np.minimum(b1[...,3], b2[...,3])
    inter = np.maximum(0, xi2-xi1) * np.maximum(0, yi2-yi1)
    a1 = (b1[...,2]-b1[...,0]) * (b1[...,3]-b1[...,1])
    a2 = (b2[...,2]-b2[...,0]) * (b2[...,3]-b2[...,1])
    return 1 - inter / (a1 + a2 - inter + 1e-6)


def _cosine_distance(f1, f2):
    f1 = f1 / (np.linalg.norm(f1, axis=1, keepdims=True) + 1e-6)
    f2 = f2 / (np.linalg.norm(f2, axis=1, keepdims=True) + 1e-6)
    return 1 - np.dot(f1, f2.T)


class LongTermMemory:
    def __init__(self, max_identities=200, similarity_threshold=0.50,
                 features_per_id=128, quality_threshold=0.4):
        self.memory               = {}
        self.max_identities       = max_identities
        self.similarity_threshold = similarity_threshold
        self.features_per_id      = features_per_id
        self.quality_threshold    = quality_threshold

    def add_identity(self, track_id, feature, frame_num, quality=1.0):
        if quality < self.quality_threshold: return
        if track_id not in self.memory:
            self.memory[track_id] = {
                'features': deque([feature], maxlen=self.features_per_id),
                'last_seen': frame_num, 'total_appearances': 1, 'first_seen': frame_num
            }
        else:
            self.memory[track_id]['features'].append(feature)
            self.memory[track_id]['last_seen'] = frame_num
            self.memory[track_id]['total_appearances'] += 1

    def search_memory(self, feature, current_frame):
        best_id, best_score = None, self.similarity_threshold
        for tid, data in self.memory.items():
            stored = np.array(list(data['features']))
            sims   = np.dot(stored, feature)
            score  = 0.6 * np.mean(sims) + 0.4 * np.max(sims)
            if score > best_score:
                best_score = score; best_id = tid
        return best_id

    def cleanup_memory(self, current_frame, max_age=1000):
        if len(self.memory) > self.max_identities:
            sorted_ids = sorted(self.memory.items(),
                                key=lambda x: (x[1]['last_seen'], x[1]['total_appearances']))
            for tid, _ in sorted_ids[:len(self.memory) - self.max_identities]:
                del self.memory[tid]

    def get_memory_summary(self):
        if not self.memory: return "Memory: Empty"
        return (f"Memory: {len(self.memory)} IDs, "
                f"{sum(len(d['features']) for d in self.memory.values())} features")


