def _make_palette(n=200):
    np.random.seed(42)
    palette = []
    for i in range(n):
        hue = (i * 0.618033988749895) % 1.0
        rgb = tuple(int(x*255) for x in plt.cm.hsv(hue)[:3])
        palette.append(rgb)
    return palette

