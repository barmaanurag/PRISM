def upload_images(role: str, source_paths=None, source_dir=None):
    """
    Copy reference images for a role ('patient' or 'caregiver') into the
    local  dataset/<role>/  folder so that FaceIdentityManager can build
    a face gallery.

    Usage (option A – explicit file list):
        upload_images('patient', source_paths=['photo1.jpg', 'photo2.png'])

    Usage (option B – copy everything from a directory):
        upload_images('caregiver', source_dir='C:/Users/Me/caregiver_photos')

    If neither argument is given, the function lists supported images
    already present in the target folder.
    """
    if role not in ('patient', 'caregiver'):
        print(f"❌ Invalid role '{role}'. Use 'patient' or 'caregiver'."); return

    target_dir = os.path.join('dataset', role)
    os.makedirs(target_dir, exist_ok=True)

    IMAGE_EXTS = {'.jpg', '.jpeg', '.png', '.bmp', '.webp'}
    copied = 0

    # Option A: explicit list of file paths
    if source_paths:
        for p in source_paths:
            if not os.path.isfile(p):
                print(f"  ⚠️  File not found, skipping: {p}"); continue
            ext = os.path.splitext(p)[1].lower()
            if ext not in IMAGE_EXTS:
                print(f"  ⚠️  Unsupported format ({ext}), skipping: {p}"); continue
            shutil.copy2(p, target_dir)
            copied += 1
            print(f"  ✓ Copied {os.path.basename(p)} → {target_dir}")

    # Option B: copy all images from a source directory
    elif source_dir:
        if not os.path.isdir(source_dir):
            print(f"❌ Source directory not found: {source_dir}"); return
        for fname in sorted(os.listdir(source_dir)):
            ext = os.path.splitext(fname)[1].lower()
            if ext in IMAGE_EXTS:
                shutil.copy2(os.path.join(source_dir, fname), target_dir)
                copied += 1
                print(f"  ✓ Copied {fname} → {target_dir}")

    # Show current state of the target folder
    existing = [f for f in os.listdir(target_dir)
                if os.path.splitext(f)[1].lower() in IMAGE_EXTS]
    print(f"\n  📂 {target_dir}: {len(existing)} image(s) total"
          f"  (newly copied: {copied})")
    if not existing:
        print(f"  ⚠️  No images found in {target_dir}. "
              f"Add reference photos before running the pipeline.")


