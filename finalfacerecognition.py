class EnhancedFeatureExtractor(FeatureExtractor):
    def __init__(self, model_path='best_model.onnx', device='cpu',
                 buffer_size=100, min_feature_quality=0.3):
        super().__init__(model_path, device)
        self.appearance_buffer  = []
        self.buffer_size        = buffer_size
        self.min_feature_quality = min_feature_quality
        self.use_multiscale     = True

    def assess_crop_quality(self, crop):
        if crop.size == 0: return 0.0
        h, w = crop.shape[:2]
        if h < 40 or w < 20: return 0.1
        aspect       = h / (w + 1e-6)
        aspect_score = max(0, min(1, 1.0 - abs(aspect - 2.0) / 2.0))
        gray         = cv2.cvtColor(crop, cv2.COLOR_BGR2GRAY)
        blur_score   = min(1.0, cv2.Laplacian(gray, cv2.CV_64F).var() / 100.0)
        bright_score = 1.0 - abs(np.mean(gray) - 128) / 128
        return aspect_score * 0.4 + blur_score * 0.4 + bright_score * 0.2

    def extract_multiscale(self, crop):
        feats = []
        for scale_crop in [crop]:
            r = cv2.resize(scale_crop, (self.size[1], self.size[0]))
            rgb = cv2.cvtColor(r, cv2.COLOR_BGR2RGB)
            t = (np.transpose(rgb, (2,0,1)).astype(np.float32)/255.0)[np.newaxis, ...]
            t = (t - self.mean) / self.std
            feats.append(self.ort_session.run(None, {'input': t})[0][0])

        if self.assess_crop_quality(crop) < 0.6 and self.use_multiscale:
            h, w = crop.shape[:2]
            zoom = crop[int(h*.1):int(h*.9), int(w*.1):int(w*.9)]
            if zoom.size > 0:
                r = cv2.resize(zoom, (self.size[1], self.size[0]))
                rgb = cv2.cvtColor(r, cv2.COLOR_BGR2RGB)
                t = (np.transpose(rgb, (2,0,1)).astype(np.float32)/255.0)[np.newaxis, ...]
                t = (t - self.mean) / self.std
                feats.append(self.ort_session.run(None, {'input': t})[0][0])

        return np.mean(np.stack(feats, axis=0), axis=0)

    def extract(self, img, bboxes, return_quality=False):
        if len(bboxes) == 0:
            return (np.empty((0,128)), []) if return_quality else np.empty((0,128))
        crops, qualities = [], []
        for bbox in bboxes:
            x1,y1,x2,y2 = map(int, bbox)
            x1,y1 = max(0,x1), max(0,y1)
            x2,y2 = min(img.shape[1],x2), min(img.shape[0],y2)
            crop = img[y1:y2, x1:x2]
            if crop.size > 0:
                crops.append(crop); qualities.append(self.assess_crop_quality(crop))
            else:
                crops.append(np.zeros((64,64,3), dtype=np.uint8)); qualities.append(0.0)

        feats = []
        for crop, q in zip(crops, qualities):
            if q > self.min_feature_quality:
                feats.append(self.extract_multiscale(crop))
            else:
                batch = self.preprocess([crop])
                ort_out = self.ort_session.run(None, {'input': batch})[0]
                feats.append(ort_out[0])
        features = np.stack(feats, axis=0)
        return (features, qualities) if return_quality else features

