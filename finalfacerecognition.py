def run_patient_caregiver_tracking(
    video_path        = 'input_video.mp4',
    output_path       = 'output_role_tracked.mp4',
    reid_model_path   = 'best_model.pth',
    dataset_dir       = 'dataset',
    conf_threshold    = 0.4,
    max_frames        = None,
    show_trajectories = True
):
    """
    End-to-end function: reads video, runs tracking + role identification,
    writes annotated output video.

    Parameters
    ----------
    video_path      : path to input video (mp4 / avi / …)
    output_path     : where to write the annotated output
    reid_model_path : your custom .pth Re-ID model
    dataset_dir     : root folder containing dataset/patient/ and dataset/caregiver/
    conf_threshold  : YOLO detection confidence cutoff
    max_frames      : process only this many frames (None = all)
    show_trajectories: draw motion trail on tracked persons
    """

    # ── pre-flight checks ────────────────────────────────────────────────────
    for path, name in [(video_path,'Video'), (reid_model_path,'Re-ID model')]:
        if not os.path.exists(path):
            print(f"❌ {name} not found: {path}"); return

    # ── initialise components ────────────────────────────────────────────────
    role_tracker = RoleTracker(reid_model_path=reid_model_path,
                               conf_threshold=conf_threshold)
    role_tracker.build_gallery(dataset_dir=dataset_dir)

    # ── open video ───────────────────────────────────────────────────────────
    cap = cv2.VideoCapture(video_path)
    if not cap.isOpened():
        print("❌ Cannot open video"); return

    fps    = int(cap.get(cv2.CAP_PROP_FPS)) or 25
    W      = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    H      = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    total  = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    if max_frames: total = min(total, max_frames)

    print(f"\n▶  Video: {W}×{H} @ {fps} FPS  ({total} frames)")
    print(f"▶  Output: {output_path}\n")

    fourcc = cv2.VideoWriter_fourcc(*'mp4v')
    writer = cv2.VideoWriter(output_path, fourcc, fps, (W, H))

    # Persistent role map that accumulates across the video
    global_role_map = {}

    frame_idx = 0
    while True:
        ret, frame = cap.read()
        if not ret or (max_frames and frame_idx >= max_frames):
            break

        tracks, frame_role_map = role_tracker.process_frame(frame)

        # Merge new role discoveries into global map (never overwrite a lock)
        for tid, role in frame_role_map.items():
            if role is not None and tid not in global_role_map:
                global_role_map[tid] = role
        # Also pull locked roles from FaceIdentityManager
        if role_tracker.face_id_manager:
            for tid, role in role_tracker.face_id_manager.get_role_map().items():
                global_role_map[tid] = role

        # ── draw ─────────────────────────────────────────────────────────────
        vis = draw_role_tracks(frame, tracks, global_role_map)

        if show_trajectories:
            vis = draw_trajectories(vis, role_tracker.tracker, role_map=global_role_map)

        # ── HUD overlay ──────────────────────────────────────────────────────
        stats = role_tracker.tracker.get_statistics()

        patient_found   = any(r=='patient'   for r in global_role_map.values())
        caregiver_found = any(r=='caregiver' for r in global_role_map.values())

        hud_lines = [
            (f"Frame {frame_idx+1}/{total}  |  Active tracks: {len(tracks)}",
             (10, 28),  (0, 255, 0)),
            (f"Memory IDs: {stats['memory_identities']}  |  "
             f"Mem-recoveries: {stats['memory_recoveries']}",
             (10, 54),  (0, 255, 255)),
            (f"Patient {'✓ FOUND' if patient_found else '— searching'}  |  "
             f"Caregiver {'✓ FOUND' if caregiver_found else '— searching'}",
             (10, 80),  (255, 230, 100)),
        ]
        for text, pos, color in hud_lines:
            cv2.putText(vis, text, pos,
                        cv2.FONT_HERSHEY_SIMPLEX, 0.55, color, 2, cv2.LINE_AA)

        writer.write(vis)

        if (frame_idx + 1) % 30 == 0:
            print(f"  [{frame_idx+1}/{total}]  active={len(tracks)}  "
                  f"patient={'✓' if patient_found else '?'}  "
                  f"caregiver={'✓' if caregiver_found else '?'}  "
                  f"mem_recoveries={stats['memory_recoveries']}")

        frame_idx += 1

    cap.release(); writer.release()

    # ── final summary ────────────────────────────────────────────────────────
    stats = role_tracker.tracker.get_statistics()
    print("\n" + "="*70)
    print("  TRACKING COMPLETE")
    print("="*70)
    print(f"  Output video  : {output_path}")
    print(f"  Frames processed: {frame_idx}")
    print(f"  Total track IDs  : {Track._count}")
    print(f"\n  Role assignments (locked for entire video):")
    for tid, role in sorted(global_role_map.items()):
        print(f"    Track {tid:>4d}  →  {role.upper()}")
    print(f"\n  Memory statistics:")
    print(f"    {stats['memory_summary']}")
    print(f"    Memory recoveries : {stats['memory_recoveries']}")
    print(f"    Buffer recoveries : {stats['reid_buffer_recoveries']}")
    print(f"    New IDs created   : {stats['new_ids_created']}")
    print("="*70)

