class NSAKalmanFilter:
    """Noise-Scale Adaptive Kalman Filter (8-state: cx,cy,w,h,vx,vy,vw,vh)"""
    def __init__(self):
        dt = 1.0
        self.F = np.eye(8)
        for i in range(4): self.F[i, i+4] = dt
        self.H = np.eye(4, 8)
        self.Q = np.diag([1,1,1,1,0.01,0.01,0.0001,0.0001])
        self.R_base = np.diag([1.0, 1.0, 10.0, 10.0])
        self.P = np.eye(8) * 10
        self.x = np.zeros(8)

    def init(self, measurement):
        self.x[:4] = measurement

    def predict(self):
        self.x = self.F @ self.x
        self.P = self.F @ self.P @ self.F.T + self.Q
        return self.x[:4].copy()

    def update(self, measurement, confidence=1.0):
        alpha = max(0.1, min(1.0, confidence))
        R     = self.R_base / (alpha + 1e-6)
        S     = self.H @ self.P @ self.H.T + R
        K     = self.P @ self.H.T @ np.linalg.inv(S)
        innov = measurement - self.H @ self.x
        self.x = self.x + K @ innov
        self.P = (np.eye(8) - K @ self.H) @ self.P

    def get_state(self):
        return self.x[:4].copy()


class GMC:
    """Global Motion Compensation using ORB features"""
    def __init__(self, method='orb', downscale=2):
        self.method    = method
        self.downscale = downscale
        self.prevFrame = None
        self.prevKeyPoints  = None
        self.prevDescriptors = None
        if method == 'orb':
            self.detector = cv2.ORB_create(500)
            self.matcher  = cv2.BFMatcher(cv2.NORM_HAMMING)

    def apply(self, raw_frame, detections=None):
        H, W = raw_frame.shape[:2]
        frame = cv2.resize(raw_frame, (W//self.downscale, H//self.downscale))
        frame = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
        transform = np.eye(2, 3)

        if self.prevFrame is None:
            self.prevFrame = frame
            keypoints, descriptors = self.detector.detectAndCompute(frame, None)
            self.prevKeyPoints   = keypoints
            self.prevDescriptors = descriptors
            return transform

        keypoints, descriptors = self.detector.detectAndCompute(frame, None)
        if (descriptors is not None and self.prevDescriptors is not None
                and len(keypoints) > 4 and len(self.prevKeyPoints) > 4):
            matches = self.matcher.knnMatch(self.prevDescriptors, descriptors, k=2)
            good = [m for m,n in matches if m.distance < 0.75*n.distance]
            if len(good) >= 4:
                src = np.float32([self.prevKeyPoints[m.queryIdx].pt for m in good]).reshape(-1,1,2)
                dst = np.float32([keypoints[m.trainIdx].pt for m in good]).reshape(-1,1,2)
                M, _ = cv2.estimateAffinePartial2D(src, dst, method=cv2.RANSAC)
                if M is not None:
                    transform = M.copy()
                    transform[:, 2] *= self.downscale

        self.prevFrame       = frame
        self.prevKeyPoints   = keypoints
        self.prevDescriptors = descriptors
        return transform


class Track:
    _count = 0

    def __init__(self, bbox, feature, track_id=None):
        if track_id is None:
            Track._count += 1
            self.track_id = Track._count
        else:
            self.track_id = track_id

        x1,y1,x2,y2 = bbox
        cx,cy = (x1+x2)/2, (y1+y2)/2
        w,h   = x2-x1, y2-y1

        self.kf = NSAKalmanFilter()
        self.kf.init(np.array([cx, cy, w, h]))
        self.features       = deque([feature], maxlen=30)
        self.hits           = 1
        self.age            = 1
        self.time_since_update = 0
        self.state          = 'tentative'
        self.trajectory     = deque(maxlen=30)
        self.trajectory.append((cx, cy))

    def predict(self):
        self.age += 1
        self.time_since_update += 1
        return self._xywh_to_xyxy(self.kf.predict())

    def update(self, bbox, feature, confidence=1.0):
        x1,y1,x2,y2 = bbox
        cx,cy = (x1+x2)/2, (y1+y2)/2
        w,h   = x2-x1, y2-y1
        self.kf.update(np.array([cx,cy,w,h]), confidence=confidence)
        self.features.append(feature)
        self.trajectory.append((cx, cy))
        self.hits += 1
        self.time_since_update = 0
        if self.state == 'tentative' and self.hits >= 3:
            self.state = 'confirmed'

    def mark_missed(self):
        if self.state == 'tentative':
            self.state = 'deleted'
        elif self.time_since_update > 30:
            self.state = 'deleted'

    def get_state(self):
        return self._xywh_to_xyxy(self.kf.get_state())

    def get_feature(self):
        return np.mean(self.features, axis=0)

    @staticmethod
    def _xywh_to_xyxy(xywh):
        cx,cy,w,h = xywh
        return np.array([cx-w/2, cy-h/2, cx+w/2, cy+h/2])


class EnhancedTrack(Track):
    def __init__(self, bbox, feature, track_id=None, quality=1.0):
        super().__init__(bbox, feature, track_id)
        self.detection_confidence = 1.0
        self.feature_quality      = quality
        self.consecutive_misses   = 0
        self.is_occluded          = False
        self.occlusion_frames     = 0
        self.last_seen_frame      = 0
        self.total_detections     = 1

    def predict(self):
        self.age += 1; self.time_since_update += 1; self.consecutive_misses += 1
        self.detection_confidence *= 0.95
        if self.consecutive_misses > 3 and self.detection_confidence > 0.5:
            self.is_occluded = True; self.occlusion_frames += 1
        if self.time_since_update > 5:
            self.kf.x[4:] *= 0.9
        return self._xywh_to_xyxy(self.kf.predict())

    def update(self, bbox, feature, quality=1.0):
        self.consecutive_misses = 0; self.is_occluded = False; self.occlusion_frames = 0
        self.detection_confidence = min(1.0, self.detection_confidence + 0.1)
        self.feature_quality = quality; self.total_detections += 1
        x1,y1,x2,y2 = bbox
        cx,cy = (x1+x2)/2, (y1+y2)/2; w,h = x2-x1, y2-y1
        self.kf.update(np.array([cx,cy,w,h]), confidence=self.detection_confidence)
        self.features.append(feature); self.trajectory.append((cx,cy))
        self.hits += 1; self.time_since_update = 0
        if self.state == 'tentative' and self.hits >= 3:
            self.state = 'confirmed'

    def mark_missed(self):
        self.consecutive_misses += 1; self.detection_confidence *= 0.9
        if self.state == 'tentative':
            self.state = 'deleted'
        elif self.detection_confidence < 0.2: self.state = 'deleted'
        elif self.time_since_update > 30:     self.state = 'deleted'
        elif self.is_occluded and self.time_since_update > 15: self.state = 'deleted'

    def get_confidence(self):
        return self.detection_confidence * 0.7 + min(1.0, self.total_detections/10.0) * 0.3


